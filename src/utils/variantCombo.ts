// ----------------------------------------------------------------------------
// شناسه‌ی ترکیب مقادیر ویژگی یک تنوع را می‌سازد (مثلاً "3,7" برای
// رنگ=3 و سایز=7). این مقدار در ستون ProductVariant.comboKey ذخیره می‌شود که
// @@unique([productId, comboKey]) روی آن است — تا حتی در برخورد دو درخواست
// هم‌زمانِ ساخت یک ترکیب تکراری، خودِ دیتابیس دومی را رد کند.
// ----------------------------------------------------------------------------
export function buildComboKey(attributeValueIds: number[]): string {
  return [...attributeValueIds].sort((a, b) => a - b).join(",");
}
