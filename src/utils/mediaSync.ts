// وقتی فرانت‌اند می‌خواهد تصویر/ویدیوی متصل به یک موجودیت را حذف کند،
// مقدار مربوط به mediaId (مثلاً logoMediaId) را null می‌فرستد. اگر همان
// لحظه فیلد URL نمایشی (مثلاً logoUrl) را هم null نکنیم، URL قدیمی —
// که دیگر به هیچ Media ای وصل نیست — همچنان در پاسخ API باقی می‌ماند و
// فرانت تصویر حذف‌شده را نشان می‌دهد.
// این تابع فقط حالت null→null را همگام می‌کند؛ وقتی mediaId یک عدد واقعی
// باشد، URL همان چیزی است که خودِ فرانت (بعد از آپلود) در همان درخواست
// فرستاده است.
// ----------------------------------------------------------------------------
export function syncUrlWithMediaId<T extends Record<string, unknown>>(
  data: T,
  mediaIdField: keyof T,
  urlField: keyof T
): T {
  if (data[mediaIdField] === null) {
    return { ...data, [urlField]: null };
  }
  return data;
}
